#!/usr/bin/env python3
"""014 stated test changes (contracts/test-impact.md, class A). Parent-only.

Each row asserts the old string's exact count before anything is written; any mismatch aborts
with nothing changed. Run from the repo root:
    DRYRUN=1 python3 specs/014-gallery-combobox/evidence/test-impact-edit.py      # counts only
    python3 specs/014-gallery-combobox/evidence/test-impact-edit.py A2            # apply A2 only
    python3 specs/014-gallery-combobox/evidence/test-impact-edit.py A1
A3 (ui-baseline/index.html) and B1 (token-combobox.html) are regenerated by UiPagesUnchangedTests,
not edited here.
"""
import os
import pathlib
import sys

T = pathlib.Path("tests/Gallery.Web.Tests")

# (row, file, old, new, expected count)
ROWS = [
    ("A1", T / "LibraryEditTests.cs",
     'Regex.Match(aside, "<ul class=\\"lib-galleries\\".*?</ul>", RegexOptions.Singleline)',
     'Regex.Match(aside, "<ul class=\\"cb-tokens\\".*?</ul>", RegexOptions.Singleline)', 1),
    ("A2", T / "IndexTests.cs",
     "Assert.Equal(36, hrefs.Count); // 14 from feature 003 + 17 from 005 + 5 from 010 (stated changes, T025 and owner review 1),",
     "Assert.Equal(37, hrefs.Count); // 14 from feature 003 + 17 from 005 + 5 from 010 (stated changes, T025 and owner review 1) + 1 from 014 (TokenCombobox),", 1),
]


def main() -> int:
    want = set(sys.argv[1:]) or {r[0] for r in ROWS}
    dry = os.environ.get("DRYRUN") == "1"
    texts, bad = {}, 0
    for row, path, old, new, n in ROWS:
        if row not in want:
            continue
        text = texts.get(path) or path.read_text(encoding="utf-8")
        got = text.count(old)
        if got != n:
            print(f"FAIL {row} {path} x{got} (expected {n}): {old[:60]!r}")
            bad += 1
            continue
        texts[path] = text.replace(old, new)
        print(f"OK {row} {path} x{got}: {old[:50]!r} -> {new[:50]!r}")
    if bad:
        print("aborted, nothing written")
        return 1
    if not dry:
        for path, text in texts.items():
            path.write_text(text, encoding="utf-8")
        print(f"wrote {len(texts)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
